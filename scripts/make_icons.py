"""Writes app/icons.svg, one inline sprite with every icon of design/icons (the 84 line icons of the design
system, 24 x 24, 1.6px stroke, currentColor): <symbol id="i-<name>"> per file, used by app/js/ui/icons.js as
<svg class="icon"><use href="#i-<name>"/></svg>.

    python scripts/make_icons.py            # design/icons/*.svg -> app/icons.svg
    python scripts/make_icons.py --check    # exit 1 when the sprite differs from the files (CI)

Plain Python, no dependencies."""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'design' / 'icons'
OUT = ROOT / 'app' / 'icons.svg'
ATTRS = ('viewBox', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin')


def symbol(path):
    svg = path.read_text(encoding='utf-8')
    m = re.search(r'<svg\b([^>]*)>(.*)</svg>', svg, re.S)
    if not m:
        raise SystemExit(f'{path.name}: not an <svg> file')
    head, body = m.group(1), m.group(2).strip()
    attrs = []
    for a in ATTRS:
        v = re.search(rf'\b{a}="([^"]*)"', head)
        if v:
            attrs.append(f'{a}="{v.group(1)}"')
    body = re.sub(r'\s+', ' ', body)
    return f'  <symbol id="i-{path.stem}" {" ".join(attrs)}>{body}</symbol>'


def build():
    files = sorted(SRC.glob('*.svg'))
    if not files:
        raise SystemExit(f'no icons in {SRC}')
    lines = ['<svg xmlns="http://www.w3.org/2000/svg" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true">',
             f'  <!-- {len(files)} icons of the design system (design/icons), generated by scripts/make_icons.py: do not edit by hand -->']
    lines += [symbol(f) for f in files]
    lines.append('</svg>')
    return '\n'.join(lines) + '\n', len(files)


def main():
    sprite, n = build()
    if '--check' in sys.argv:
        current = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if current != sprite:
            print(f'{OUT.relative_to(ROOT)} differs from design/icons: run python scripts/make_icons.py')
            sys.exit(1)
        print(f'icons.svg matches design/icons ({n} icons)')
        return
    OUT.write_text(sprite, encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)} ({n} icons)')


if __name__ == '__main__':
    main()
